"""IFC ingest: units, north, georeferencing and window-to-space containment.

Milestone M2's acceptance criterion is that the fixture loads with correct
north, units and containment, so those three get the most attention here.

The fixture is generated by ``tests/fixtures/make_sample_building.py`` and is
deliberately awkward: millimetre units, true north 30 degrees off project
north, and one window with no space boundary.
"""

from __future__ import annotations

import json
import os
from pathlib import Path
from typing import Any

import ifcopenshell
import numpy as np
import pytest

from sun_study.core.orientation import SiteOrientation
from sun_study.ingest.ifc import GeoreferencingError, read_ifc
from sun_study.ingest.scene import SceneConfig, build_scene, planar_face_grid

FIXTURES = Path(__file__).resolve().parents[1] / "fixtures"
SAMPLE = FIXTURES / "sample_building.ifc"

# Values the fixture generator declares. If these drift apart the fixture has
# been regenerated with different inputs and the golden results are stale.
EXPECTED_LATITUDE = -33.75
EXPECTED_LONGITUDE = 151.25
EXPECTED_ELEVATION_M = 20.0
EXPECTED_NORTH_BEARING = 30.0
EXPECTED_UNIT_SCALE = 0.001


@pytest.fixture(scope="module")
def model() -> Any:
    return read_ifc(SAMPLE)


def test_fixture_is_committed() -> None:
    """The fixture is synthetic and committed on purpose (brief section 10)."""
    assert SAMPLE.is_file(), (
        f"{SAMPLE} is missing; regenerate with "
        f"'uv run python tests/fixtures/make_sample_building.py'"
    )


def test_committed_fixture_matches_its_generator(tmp_path: Path) -> None:
    """The .ifc must be exactly what the script produces, byte for byte.

    Catches two things that would otherwise be invisible: the committed file
    having been hand-edited, and the generator having changed without the
    fixture and its golden results being regenerated.

    This is only possible because generation is deterministic -- GUIDs come
    from a counter and the SPF header timestamp is pinned, since IfcOpenShell
    otherwise stamps the current time and every regeneration would be a diff.
    """
    import subprocess
    import sys

    script = FIXTURES / "make_sample_building.py"
    regenerated = tmp_path / "sample_building.ifc"

    source = script.read_text(encoding="utf-8").replace(
        'destination = Path(__file__).parent / "sample_building.ifc"',
        f"destination = Path({str(regenerated)!r})",
    )
    relocated = tmp_path / "generator.py"
    relocated.write_text(source, encoding="utf-8")

    subprocess.run([sys.executable, str(relocated)], check=True, capture_output=True)

    assert regenerated.read_bytes() == SAMPLE.read_bytes(), (
        "the committed fixture differs from what its generator produces; "
        "re-run 'uv run python tests/fixtures/make_sample_building.py' and "
        "regenerate the golden file with SUN_STUDY_UPDATE_GOLDEN=1"
    )


# ---------------------------------------------------------------------------
# Units -- the two scales that must not be conflated.
# ---------------------------------------------------------------------------
def test_declared_unit_is_millimetres(model: Any) -> None:
    assert model.length_unit_scale == pytest.approx(EXPECTED_UNIT_SCALE)


def test_geometry_arrives_in_metres_not_project_units(model: Any) -> None:
    """The iterator already applies the unit scale; applying it again would
    shrink a 2.4 m window to 2.4 mm."""
    windows = model.of_class("IfcWindow")
    assert len(windows) == 4

    lower, upper = windows[0].bounds
    width = float(np.max(upper - lower))
    assert width == pytest.approx(2.4, abs=1e-6), (
        f"window measures {width} across; expected 2.4 m. A value near 2400 means "
        f"the geometry is still in millimetres, and one near 0.0024 means the unit "
        f"scale has been applied twice."
    )


def test_building_extent_is_plausible_in_metres(model: Any) -> None:
    mesh = model.occluder_mesh()
    extent = mesh.vertices.max(axis=0) - mesh.vertices.min(axis=0)
    assert 20.0 < float(extent[0]) < 100.0, f"building spans {extent[0]} m across"
    assert 5.0 < float(extent[2]) < 30.0, f"building is {extent[2]} m tall"


def test_site_elevation_is_converted_from_project_units(model: Any) -> None:
    """RefElevation is an attribute, so unlike geometry it *does* need scaling.

    The fixture stores 20000 (millimetres). Reading it unscaled would place the
    site 20 km up; scaling geometry as well would put it at 20 mm.
    """
    assert model.site_elevation_m == pytest.approx(EXPECTED_ELEVATION_M)


