GOLDEN = FIXTURES / "golden_sample_building.json"


def run_fixture_pipeline() -> dict[str, dict[str, float]]:
    """The whole chain on the fixture, reduced to per-apartment minutes."""
    import datetime as dt

    from sun_study.core.analysis import summarise_by_parent, sunlit_matrix
    from sun_study.core.occlusion import Occluder
    from sun_study.core.solar import assessment_times, solar_position

    model = read_ifc(SAMPLE)
    scene = build_scene(model, SceneConfig(timezone="Australia/Sydney"))

    times = assessment_times(
        dt.date(2024, 6, 21), "Australia/Sydney", dt.time(9, 0), dt.time(15, 0), 10
    )
    suns = scene.orientation.sun_vectors(
        solar_position(times, model.latitude_deg, model.longitude_deg)
    )
    occluder = Occluder(scene.occluders)
    names = {e.global_id: e.name for e in model.elements}

    results: dict[str, dict[str, float]] = {}
    for label, points in (
        ("living_room", scene.window_samples),
        ("open_space", scene.open_space_samples),
    ):
        summary = summarise_by_parent(points, sunlit_matrix(points, occluder, suns), 10.0)
        results[label] = {
            names.get(pid, pid): round(float(minutes), 3)
            for pid, minutes in zip(summary.parent_ids, summary.cumulative_minutes, strict=True)
        }
    return results


def test_fixture_results_match_the_golden_file() -> None:
    """Regenerate deliberately with SUN_STUDY_UPDATE_GOLDEN=1, never casually.

    A change here means the numbers this tool reports for a known building have
    moved. That is either a fix or a regression, and it should never pass
    unnoticed.
    """
    actual = run_fixture_pipeline()

    if os.environ.get("SUN_STUDY_UPDATE_GOLDEN") == "1":
        GOLDEN.write_text(json.dumps(actual, indent=2, sort_keys=True) + "\n", encoding="utf-8")

    assert GOLDEN.is_file(), (
        f"{GOLDEN} is missing; create it with SUN_STUDY_UPDATE_GOLDEN=1 uv run pytest"
    )
    expected = json.loads(GOLDEN.read_text(encoding="utf-8"))

    assert actual.keys() == expected.keys()
    for section, values in expected.items():
        assert actual[section].keys() == values.keys(), f"{section} apartments changed"
        for name, minutes in values.items():
            assert actual[section][name] == pytest.approx(minutes, abs=1e-3), (
                f"{section} / {name}: {actual[section][name]} minutes, golden says {minutes}"
            )


def test_the_fixture_discriminates() -> None:
    """A golden file of four identical numbers would catch almost nothing.

    The fixture is built so the two storeys and the two sides all differ: the
    context block bites into the lower storey and the A side, and the balcony
    one level up overhangs each window. If these collapse together the fixture
    has stopped testing anything.
    """
    living = run_fixture_pipeline()["living_room"]
    values = sorted(living.values())

    assert len(set(values)) == 4, f"expected four distinct results, got {living}"
    assert values[0] < 120.0, "at least one apartment must fail the 2 hour threshold"
    assert values[-1] == pytest.approx(360.0), (
        "the top-floor unlit-side apartment should see the whole window, matching "
        "the unobstructed analytic case"
    )


# ---------------------------------------------------------------------------
# The site placement, and why it is read at all.
#
# Archicad's "Survey Point" IFC model position rotates the geometry through
# IfcSite's placement and then writes TrueNorth as (0,1), because the world
# coordinates it produces really are true-north-aligned. Its "Project Origin"
# option does the opposite. Both are correct; the analysis is unaffected
# either way because it reads world coordinates. Only a comparison against
# something *outside* the file -- a live Archicad -- needs to know which half
# of the pair carries the angle, and that is what site_rotation_deg is for.
# ---------------------------------------------------------------------------
def test_the_fixture_has_an_unrotated_site() -> None:
    """The default, and the case that keeps the cross-check arithmetic simple."""
    assert read_ifc(SAMPLE).site_rotation_deg == pytest.approx(0.0)


def _with_site_rotation(source: Path, destination: Path, degrees: float) -> Path:
    """The fixture, re-exported as though Archicad had rotated the site."""
    model = ifcopenshell.open(str(source))
    site = model.by_type("IfcSite")[0]
    radians = np.radians(degrees)
    site.ObjectPlacement.RelativePlacement.RefDirection = model.create_entity(
        "IfcDirection", DirectionRatios=(float(np.cos(radians)), float(np.sin(radians)), 0.0)
    )
    model.write(str(destination))
    return destination


def test_a_rotated_site_placement_is_read_back(tmp_path: Path) -> None:
    rotated = _with_site_rotation(SAMPLE, tmp_path / "rotated.ifc", 40.948)
    model = read_ifc(rotated)

    assert model.site_rotation_deg == pytest.approx(40.948, abs=1e-6)
    # TrueNorth is untouched, so the two are independent and both survive.
    assert model.true_north_bearing_deg % 360.0 == pytest.approx(30.0)


def test_the_site_rotation_does_not_reach_the_analysis(tmp_path: Path) -> None:
    """It is diagnostic metadata, not an input.

    ``SiteOrientation`` must keep taking its bearing from ``TrueNorth`` alone,
    because the geometry it is applied to is already in world coordinates with
    the site placement baked in. Adding the rotation here would count it twice.
    """
    rotated = _with_site_rotation(SAMPLE, tmp_path / "rotated.ifc", 40.948)
    orientation = read_ifc(rotated).orientation("Australia/Sydney")

    assert orientation.true_north_bearing_deg % 360.0 == pytest.approx(30.0)


def test_a_site_without_a_placement_reports_no_rotation(tmp_path: Path) -> None:
    """Absence must read as zero, not crash: it is the overwhelmingly common case."""
    model = ifcopenshell.open(str(SAMPLE))
    model.by_type("IfcSite")[0].ObjectPlacement = None
    stripped = tmp_path / "no_placement.ifc"
    model.write(str(stripped))

    assert read_ifc(stripped).site_rotation_deg == pytest.approx(0.0)


# ---------------------------------------------------------------------------
# Selecting living-room glazing by an ID suffix (D24), and zones by layer.
#
# The route for a practice that zones by *unit* rather than by room. There is
# then no living-room Zone to match a name against, and every window in the
# unit -- bedrooms, bathroom, kitchen -- would otherwise be counted as living
# room glazing. That does not fail; it returns an optimistically wrong number,
# which is the failure mode this project exists to avoid.
# ---------------------------------------------------------------------------
def _mark_openings(source: Path, destination: Path, suffix: str = "_L") -> Path:
    """The fixture, renamed to the ``_L`` convention, with one opening a door.

    Only the A-side openings are marked, so a test can tell selection from
    "everything matched". ``LongName`` is stripped from every space as well:
    with no room named "Living Room" anywhere, anything the scene finds must
    have come through the suffix.
    """
    model = ifcopenshell.open(str(source))

    for space in model.by_type("IfcSpace"):
        space.LongName = None

    windows = sorted(model.by_type("IfcWindow"), key=lambda w: w.Name)
    for window in windows:
        if "-A" in (window.Name or ""):
            window.Name = f"{window.Name}{suffix}"

    # Turn one marked window into a door in place. A balcony slider is a Door
    # in Archicad, and doors were 110 of 252 marked openings in the reference
    # project -- reading windows alone would drop nearly half the glazing.
    victim = next(w for w in windows if (w.Name or "").endswith(suffix))
    door = model.create_entity(
        "IfcDoor",
        GlobalId=victim.GlobalId,
        OwnerHistory=victim.OwnerHistory,
        Name=victim.Name,
        ObjectPlacement=victim.ObjectPlacement,
        Representation=victim.Representation,
        OverallHeight=victim.OverallHeight,
        OverallWidth=victim.OverallWidth,
    )
    for relation in model.by_type("IfcRelContainedInSpatialStructure"):
        relation.RelatedElements = tuple(
            door if e.id() == victim.id() else e for e in relation.RelatedElements
        )
    model.remove(victim)

    model.write(str(destination))
    return destination


