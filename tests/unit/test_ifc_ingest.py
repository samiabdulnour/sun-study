def _strip_and_write(destination: Path, mutate: Any) -> Path:
    file = ifcopenshell.open(str(SAMPLE))
    mutate(file)
    file.write(str(destination))
    return destination


def test_missing_true_north_raises(tmp_path: Path) -> None:
    def remove_north(file: Any) -> None:
        for context in file.by_type("IfcGeometricRepresentationContext", include_subtypes=False):
            context.TrueNorth = None

    path = _strip_and_write(tmp_path / "no_north.ifc", remove_north)
    with pytest.raises(GeoreferencingError, match="North Direction"):
        read_ifc(path)


def test_missing_latitude_raises(tmp_path: Path) -> None:
    def remove_location(file: Any) -> None:
        for site in file.by_type("IfcSite"):
            site.RefLatitude = None
            site.RefLongitude = None

    path = _strip_and_write(tmp_path / "no_location.ifc", remove_location)
    with pytest.raises(GeoreferencingError, match="Project Location"):
        read_ifc(path)


def test_ambiguous_multiple_located_sites_raises(tmp_path: Path) -> None:
    """Two georeferenced sites means the tool cannot know which one governs."""

    def duplicate_site(file: Any) -> None:
        original = file.by_type("IfcSite")[0]
        file.create_entity(
            "IfcSite",
            GlobalId=ifcopenshell.guid.new(),
            Name="Second Site",
            RefLatitude=original.RefLatitude,
            RefLongitude=original.RefLongitude,
            RefElevation=original.RefElevation,
        )

    path = _strip_and_write(tmp_path / "two_sites.ifc", duplicate_site)
    with pytest.raises(GeoreferencingError, match="ambiguous"):
        read_ifc(path)


def test_missing_file_raises() -> None:
    with pytest.raises(FileNotFoundError):
        read_ifc(FIXTURES / "does_not_exist.ifc")


def test_ifcopenshell_helper_would_have_defaulted_silently() -> None:
    """Why this module does not use ``get_true_north`` for the presence check.

    The helper returns 0 for a file with no TrueNorth, which is indistinguishable
    from a project genuinely aligned to true north. That is the silent default
    the brief forbids, so this pins the behaviour we are deliberately avoiding.
    """
    import ifcopenshell.util.geolocation

    file = ifcopenshell.open(str(SAMPLE))
    for context in file.by_type("IfcGeometricRepresentationContext", include_subtypes=False):
        context.TrueNorth = None

    assert ifcopenshell.util.geolocation.get_true_north(file) == 0


