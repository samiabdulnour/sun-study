    spaces = model.of_class("IfcSpace")
    assert all(space.long_name == "Living Room" for space in spaces)
    assert all(space.name.startswith("Apartment") for space in spaces)

    scene = build_scene(model, SceneConfig(timezone="Australia/Sydney"))
    assert scene.provenance["living_rooms_matched"] == 4
    assert scene.provenance["windows_assessed"] == 4


