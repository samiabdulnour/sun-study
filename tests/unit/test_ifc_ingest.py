# ---------------------------------------------------------------------------
# Golden results -- fail CI on drift (brief section 7).
# ---------------------------------------------------------------------------
GOLDEN = FIXTURES / "golden_sample_building.json"


def run_fixture_pipeline() -> dict[str, dict[str, float]]:
    """The whole chain on the fixture, reduced to per-apartment minutes."""
    import datetime as dt

    from sun_study.core.analysis import summarise_by_parent, sunlit_matrix
    from sun_study.core.occlusion import Occluder
    from sun_study.core.solar import assessment_times, solar_position

    model = read_ifc(SAMPLE)
    scene = build_scene(model, SceneConfig(timezone="Australia/Sydney"))

    times = assessment_times(
        dt.date(2024, 6, 21), "Australia/Sydney", dt.time(9, 0), dt.time(15, 0), 10
    )
    suns = scene.orientation.sun_vectors(
        solar_position(times, model.latitude_deg, model.longitude_deg)
    )
    occluder = Occluder(scene.occluders)
    names = {e.global_id: e.name for e in model.elements}

    results: dict[str, dict[str, float]] = {}
    for label, points in (
        ("living_room", scene.window_samples),
        ("open_space", scene.open_space_samples),
    ):
        summary = summarise_by_parent(points, sunlit_matrix(points, occluder, suns), 10.0)
        results[label] = {
            names.get(pid, pid): round(float(minutes), 3)
            for pid, minutes in zip(summary.parent_ids, summary.cumulative_minutes, strict=True)
        }
    return results


def test_fixture_results_match_the_golden_file() -> None:
    """Regenerate deliberately with SUN_STUDY_UPDATE_GOLDEN=1, never casually.

    A change here means the numbers this tool reports for a known building have
    moved. That is either a fix or a regression, and it should never pass
    unnoticed.
    """
    actual = run_fixture_pipeline()

    if os.environ.get("SUN_STUDY_UPDATE_GOLDEN") == "1":
        GOLDEN.write_text(json.dumps(actual, indent=2, sort_keys=True) + "\n", encoding="utf-8")

    assert GOLDEN.is_file(), (
        f"{GOLDEN} is missing; create it with SUN_STUDY_UPDATE_GOLDEN=1 uv run pytest"
    )
    expected = json.loads(GOLDEN.read_text(encoding="utf-8"))

    assert actual.keys() == expected.keys()
    for section, values in expected.items():
        assert actual[section].keys() == values.keys(), f"{section} apartments changed"
        for name, minutes in values.items():
            assert actual[section][name] == pytest.approx(minutes, abs=1e-3), (
                f"{section} / {name}: {actual[section][name]} minutes, golden says {minutes}"
            )


def test_the_fixture_discriminates() -> None:
    """A golden file of four identical numbers would catch almost nothing.

    The fixture is built so the two storeys and the two sides all differ: the
    context block bites into the lower storey and the A side, and the balcony
    one level up overhangs each window. If these collapse together the fixture
    has stopped testing anything.
    """
    living = run_fixture_pipeline()["living_room"]
    values = sorted(living.values())

    assert len(set(values)) == 4, f"expected four distinct results, got {living}"
    assert values[0] < 120.0, "at least one apartment must fail the 2 hour threshold"
    assert values[-1] == pytest.approx(360.0), (
        "the top-floor unlit-side apartment should see the whole window, matching "
        "the unobstructed analytic case"
    )
