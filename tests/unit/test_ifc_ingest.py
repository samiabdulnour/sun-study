"""IFC ingest: units, north, georeferencing and window-to-space containment.

Milestone M2's acceptance criterion is that the fixture loads with correct
north, units and containment, so those three get the most attention here.

The fixture is generated by ``tests/fixtures/make_sample_building.py`` and is
deliberately awkward: millimetre units, true north 30 degrees off project
north, and one window with no space boundary.
"""

