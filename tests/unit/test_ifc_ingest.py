FIXTURES = Path(__file__).resolve().parents[1] / "fixtures"
SAMPLE = FIXTURES / "sample_building.ifc"

# Values the fixture generator declares. If these drift apart the fixture has
# been regenerated with different inputs and the golden results are stale.
EXPECTED_LATITUDE = -33.75
EXPECTED_LONGITUDE = 151.25
EXPECTED_ELEVATION_M = 20.0
EXPECTED_NORTH_BEARING = 30.0
EXPECTED_UNIT_SCALE = 0.001


@pytest.fixture(scope="module")
def model() -> Any:
    return read_ifc(SAMPLE)


def test_fixture_is_committed() -> None:
    """The fixture is synthetic and committed on purpose (brief section 10)."""
    assert SAMPLE.is_file(), (
        f"{SAMPLE} is missing; regenerate with "
        f"'uv run python tests/fixtures/make_sample_building.py'"
    )


def test_committed_fixture_matches_its_generator(tmp_path: Path) -> None:
    """The .ifc must be exactly what the script produces, byte for byte.

    Catches two things that would otherwise be invisible: the committed file
    having been hand-edited, and the generator having changed without the
    fixture and its golden results being regenerated.

    This is only possible because generation is deterministic -- GUIDs come
    from a counter and the SPF header timestamp is pinned, since IfcOpenShell
    otherwise stamps the current time and every regeneration would be a diff.
    """
    import subprocess
    import sys

    script = FIXTURES / "make_sample_building.py"
    regenerated = tmp_path / "sample_building.ifc"

    source = script.read_text(encoding="utf-8").replace(
        'destination = Path(__file__).parent / "sample_building.ifc"',
        f"destination = Path({str(regenerated)!r})",
    )
    relocated = tmp_path / "generator.py"
    relocated.write_text(source, encoding="utf-8")

    subprocess.run([sys.executable, str(relocated)], check=True, capture_output=True)

    assert regenerated.read_bytes() == SAMPLE.read_bytes(), (
        "the committed fixture differs from what its generator produces; "
        "re-run 'uv run python tests/fixtures/make_sample_building.py' and "
        "regenerate the golden file with SUN_STUDY_UPDATE_GOLDEN=1"
    )


